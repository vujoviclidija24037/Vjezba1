package Java33;

public class Unazad {
	public static void main(String[] args) {
		
		int [] niz= new int[10];
		
		for(int i=0;i<niz.length;i++) {
			niz[i]=i+1;
			
			//ispis ovog niza unazad
			
		for(int i1=niz.length-1; i1>=0;i1--) {
			System.out.println(niz[i1]+ "");
			
		}
		
		System.out.println();
		}
		
	}

}
